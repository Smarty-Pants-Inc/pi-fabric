// smarty-dev#1246: workflow-authored markers cannot authorize hosted runners.
// The only reviewed exception is Paul's PR-time Windows check; remove it after
// smarty-dev#3580 assigns the automatic fix-or-revert owner, then use Option A.
import fs from "node:fs";
import path from "node:path";
import { isDeepStrictEqual } from "node:util";
import { LineCounter, parseDocument, visit } from "yaml";

const windowsException = {
  workflow: "test.yml",
  job: "windows",
  name: "check (windows-latest)",
  runner: "windows-latest",
  condition: "github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository",
  marker: "# hosted-exception: PR-time windows-latest kept by Paul 2026-10-03 (pi-fabric#254 5964538892); exit: post-merge Windows run gets an automatic fix-or-revert owner (smarty-dev#3580), then Option A (Dev3 main-only)",
};

// Same label rule as the canonical factory detective check, smarty-dev setup/factory/actions_minutes.py HOSTED
// (dev-lead, smarty-dev#1246): the two must never disagree.
const hostedLabel = /(?<![\w.-])(?:ubuntu|macos|windows)-[\w.-]*\w/i;
const expression = /^\$\{\{\s*([\s\S]*?)\s*\}\}$/;
const MAX_ROWS = 256; // GitHub Actions' maximum jobs generated by a matrix.
const fail = (message) => { throw new Error(message); };
const mapping = (value, context) => {
  if (!(value instanceof Map) || [...value.keys()].some((key) => typeof key !== "string" || key === "<<")) {
    fail(`unsupported ${context}: expected a mapping with string keys (no YAML merges)`);
  }
  return value;
};
const getPath = (value, keys) => {
  for (const key of keys) {
    if (!(value instanceof Map) || !value.has(key)) fail(`unresolved matrix.${keys.join(".")}`);
    value = value.get(key);
  }
  return value;
};
const matches = (row, pattern) => [...pattern].every(([key, value]) => row.has(key) && isDeepStrictEqual(row.get(key), value));

// Expand static matrices using Actions' axes/include/exclude semantics. Unknown or
// dynamic matrix forms cannot establish a safe runner set and are rejected.
function matrixRows(job) {
  const strategy = mapping(job.get("strategy"), "strategy");
  const matrix = mapping(strategy.get("matrix"), "matrix");
  const axes = [...matrix].filter(([key]) => key !== "include" && key !== "exclude");
  let originals = [new Map()];
  for (const [key, values] of axes) {
    if (!Array.isArray(values) || values.length === 0) fail(`unsupported matrix axis ${key}`);
    if (originals.length * values.length > MAX_ROWS) fail("matrix exceeds 256 combinations");
    originals = originals.flatMap((row) => values.map((value) => new Map([...row, [key, value]])));
  }
  const entries = (key) => {
    if (!matrix.has(key)) return [];
    const values = matrix.get(key);
    if (!Array.isArray(values)) fail(`unsupported matrix.${key}`);
    return values.map((value) => mapping(value, `matrix.${key} entry`));
  };
  const exclusions = entries("exclude");
  for (const excluded of exclusions) {
    if ([...excluded.keys()].some((key) => !axes.some(([axis]) => axis === key))) fail("unsupported matrix.exclude key");
  }
  originals = axes.length ? originals.filter((row) => !exclusions.some((excluded) => matches(row, excluded))) : [];
  const rows = originals.map((row) => new Map(row));
  for (const included of entries("include")) {
    let applied = false;
    originals.forEach((original, index) => {
      if ([...included].every(([key, value]) => !original.has(key) || isDeepStrictEqual(original.get(key), value))) {
        for (const [key, value] of included) rows[index].set(key, value);
        applied = true;
      }
    });
    if (!applied) rows.push(new Map(included));
    if (rows.length > MAX_ROWS) fail("matrix exceeds 256 combinations");
  }
  if (rows.length === 0) fail("matrix has no resolvable combinations");
  return rows;
}

function expressionValues(value, job, rows) {
  const match = expression.exec(value);
  if (!match) fail(`unsupported runner expression: ${value}`);
  const body = match[1];
  // Only statically enumerable matrix paths and constant strings are supported.
  // Conditionals, functions, contexts, bracket access and interpolation fail closed.
  if (/^matrix\.[A-Za-z_][A-Za-z0-9_-]*(?:\.[A-Za-z_][A-Za-z0-9_-]*)*$/.test(body)) {
    rows.value ??= matrixRows(job);
    return rows.value.map((row) => getPath(row, body.slice(7).split(".")));
  }
  if (/^'(?:[^']|'')*'$/.test(body)) return [body.slice(1, -1).replace(/''/g, "'")];
  fail(`unsupported runner expression: ${value}`);
}

function validateRunner(value, job, rows, kind = "selector", depth = 0) {
  if (depth > 20) fail("unsupported recursive runner selector");
  if (typeof value === "string") {
    if (value.includes("${{") || value.includes("}}")) {
      for (const resolved of expressionValues(value, job, rows)) validateRunner(resolved, job, rows, kind, depth + 1);
      return;
    }
    const label = value.trim(); // Folded and literal scalars may carry a trailing newline.
    if (!label || /[\r\n]/.test(label)) fail("unsupported empty or multiline runner label");
    if (hostedLabel.test(label)) fail(`unapproved hosted runner: ${label}`);
    return;
  }
  if (Array.isArray(value) && (kind === "selector" || kind === "labels")) {
    if (value.length === 0) fail("unsupported empty runner labels");
    for (const label of value) {
      // A complete expression may resolve to a list; list elements must resolve to strings.
      validateRunner(label, job, rows, "label", depth + 1);
      if (typeof label !== "string") fail("unsupported non-string runner label");
    }
    return;
  }
  if (value instanceof Map && kind === "selector") {
    const selector = mapping(value, "runs-on");
    if (selector.size === 0 || [...selector.keys()].some((key) => key !== "group" && key !== "labels")) {
      fail("unsupported runs-on object: expected group and/or labels");
    }
    if (selector.has("group")) validateRunner(selector.get("group"), job, rows, "group", depth + 1);
    if (selector.has("labels")) validateRunner(selector.get("labels"), job, rows, "labels", depth + 1);
    return;
  }
  fail(`unsupported runs-on ${kind}: expected a string${kind === "group" ? "" : ", label list or group/labels object"}`);
}

let failed = false;
for (const filename of process.argv.slice(2)) {
  let line = 1;
  const report = (message) => {
    console.error(`${filename}:${line}: ${message}`);
    failed = true;
  };
  try {
    const source = fs.readFileSync(filename, "utf8");
    const sourceLines = source.split(/\r?\n/);
    const approvedMarkers = new Set();
    line = 1;
    const lineCounter = new LineCounter();
    const document = parseDocument(source, { lineCounter, uniqueKeys: true, merge: false });
    // Unresolved/custom tags and duplicate keys cannot be silently accepted.
    for (const error of [...document.errors, ...document.warnings]) {
      line = error.linePos?.[0]?.line ?? 1;
      report(`invalid workflow YAML: ${error.message}`);
    }
    if (document.errors.length || document.warnings.length) continue;
    visit(document, { Pair(_key, pair) {
      if (pair.key?.value === "<<") fail("unsupported YAML merge key");
    } });
    const root = mapping(document.toJS({ mapAsMap: true, maxAliasCount: 100 }), "workflow");
    const jobs = mapping(root.get("jobs"), "jobs");
    if (jobs.size === 0) fail("workflow has no jobs");
    for (const [name, value] of jobs) {
      const node = document.getIn(["jobs", name, "runs-on"], true) ?? document.getIn(["jobs", name], true);
      line = node?.range ? lineCounter.linePos(node.range[0]).line : 1;
      try {
        const job = mapping(value, `job ${name}`);
        if (!job.has("runs-on")) {
          // Reusable workflows delegate runner selection; no local selector exists.
          if (typeof job.get("uses") === "string" && job.get("uses").trim()) continue;
          fail(`job ${name} has no runs-on`);
        }
        // Bind the recorded marker to this exact workflow/job/selector/condition,
        // immediately before runs-on. A copied marker cannot approve another job,
        // a matrix, an expression, a label list, or another hosted image.
        const approved = path.basename(filename) === windowsException.workflow
          && name === windowsException.job
          && job.get("name") === windowsException.name
          && job.get("if") === windowsException.condition
          && job.get("runs-on") === windowsException.runner
          && !job.has("strategy")
          && sourceLines[line - 2]?.trim() === windowsException.marker;
        if (approved) approvedMarkers.add(line - 1);
        else validateRunner(job.get("runs-on"), job, {});
      } catch (error) {
        report(error.message);
      }
    }
    sourceLines.forEach((text, index) => {
      if (/^\s*#\s*hosted-exception\s*:/.test(text) && !approvedMarkers.has(index + 1)) {
        line = index + 1;
        report("hosted-exception marker forbidden: not an allowlisted exception");
      }
    });
  } catch (error) {
    report(`cannot validate workflow: ${error.message}`);
  }
}
if (process.argv.length < 3) {
  console.error("No workflow paths supplied");
  failed = true;
}
process.exitCode = failed ? 1 : 0;
